#!/usr/bin/env python3
"""news-image-20261120 v4.4 entrypoint.

Produces entry.png (1024x1024) in $MAKEFUN_OUTPUT_DIR (default
/output) and, when possible, in the current working directory.

If entry.png already sits next to this file, it is used byte for
byte. Otherwise the image is generated by running the bundled
draw_v4.py (its fonts live in fonts/, so no system fonts are
needed). The cwd copy is best-effort: a read-only cwd never fails
the run. Deterministic: no network, no clock, no randomness.
"""
import hashlib
import os
import shutil
import subprocess
import sys


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _write(src, dst):
    if os.path.abspath(src) == os.path.abspath(dst):
        return dst
    shutil.copyfile(src, dst)
    return dst


def _generate(here):
    """Run draw_v4.py so entry.png exists; return its path or None.

    First try in place (it writes entry.png next to itself). If that
    fails — e.g. the script directory is read-only — copy the
    generator and its bundled fonts to a temp dir and run it there.
    """
    script = os.path.join(here, "draw_v4.py")
    try:
        subprocess.run([sys.executable, script], check=True)
    except (OSError, subprocess.CalledProcessError):
        pass
    else:
        cand = os.path.join(here, "entry.png")
        if os.path.exists(cand):
            return cand
    try:
        import tempfile
        tmp = tempfile.mkdtemp(prefix="news-image-")
        shutil.copytree(os.path.join(here, "fonts"),
                        os.path.join(tmp, "fonts"))
        shutil.copyfile(script, os.path.join(tmp, "draw_v4.py"))
        subprocess.run([sys.executable, os.path.join(tmp, "draw_v4.py")],
                       check=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    cand = os.path.join(tmp, "entry.png")
    return cand if os.path.exists(cand) else None


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    if not os.path.exists(src):
        # No pre-rendered image: generate it from the bundled script.
        src = _generate(here)
    if not src or not os.path.exists(src):
        print("error: entry.png was not produced", file=sys.stderr)
        return 1

    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    written = None
    # Main output first; fall back to cwd, then to this directory,
    # so a write problem in one place never fails the run.
    for target_dir in (out_dir, os.getcwd(), here):
        try:
            os.makedirs(target_dir, exist_ok=True)
            written = _write(src, os.path.join(target_dir, "entry.png"))
            break
        except OSError:
            continue
    if written is None:
        print("error: could not write entry.png anywhere", file=sys.stderr)
        return 1
    # Best-effort cwd copy (skipped when it is already the output).
    try:
        _write(src, os.path.join(os.getcwd(), "entry.png"))
    except OSError:
        pass
    print("entry.png ready: %s  %d bytes  sha256=%s" % (
        written, os.path.getsize(written), _sha256(written)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
